export const getCollection = (id) => COLLECTIONS.find(c => c.id === id);
export const getCarteById = (carteId) => {
  for (const col of COLLECTIONS) {
    const carte = col.cartes.find(c => c.id === carteId);
    if (carte) return { ...carte, dossier: col.dossier, collection: col.nom };
  }
  return null;
};
export const getImagePath = (collection, fichier) => `${collection.dossier}/${fichier}`;
export const getTotalCartes = () => COLLECTIONS.reduce((acc, c) => acc + c.cartes.length, 0);