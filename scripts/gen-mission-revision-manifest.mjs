import fs from "fs";
import path from "path";

const root = path.resolve("src/data");
const dirs = [
  path.join(root, "sdgn/chapters"),
  path.join(root, "management/chapters"),
];
const ids = [];
for (const dir of dirs) {
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith(".ts")) continue;
    const text = fs.readFileSync(path.join(dir, file), "utf8");
    for (const m of text.matchAll(/id:\s*"([^"]+)"/g)) ids.push(m[1]);
  }
}
ids.sort();
const out = path.join(root, "missionRevisionManifest.ts");
const body = `/** Auto-generated by scripts/gen-mission-revision-manifest.mjs */
export const MISSION_EXERCISE_CONTENT_REVISION = 2 as const;

/** Exercise IDs with updated content (1 jeton chance per revision). */
export const MISSION_EXERCISE_IDS_AT_REVISION_2 = new Set<string>([
${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
]);
`;
fs.writeFileSync(out, body, "utf8");
console.log(`Wrote ${out} (${ids.length} exercise ids)`);
