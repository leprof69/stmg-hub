// Sort by broken length descending to avoid partial overlaps
REPLACEMENTS.sort((a, b) => b[1].length - a[1].length);

function fixContent(content) {
  let out = content;
  for (const [good, bad] of REPLACEMENTS) {
    if (out.includes(bad)) out = out.split(bad).join(good);
  }
  return out;
}

function walk(dir, files = []) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) {
      if (!["node_modules", "dist"].includes(name)) walk(p, files);
    } else if (/\.(tsx?|ts|css)$/.test(name)) files.push(p);
  }
  return files;
}

let changed = 0;
let remaining = 0;
const remainFiles = [];

for (const file of walk(ROOT)) {
  const raw = fs.readFileSync(file, "utf8");
  const fixed = fixContent(raw);
  const n = fixed.split(R).length - 1;
  if (fixed !== raw) {
    fs.writeFileSync(file, fixed, "utf8");
    console.log("fixed:", path.relative(ROOT, file), n ? `(still ${n} FFFD)` : "(clean)");
    changed++;
  }
  if (n) {
    remaining += n;
    remainFiles.push({ file: path.relative(ROOT, file), n });
  }
}

